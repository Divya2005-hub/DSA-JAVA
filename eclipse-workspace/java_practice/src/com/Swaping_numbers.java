package com;

public class Swaping_numbers {
	public static void main(String[] args) {
		int a=1;
		int b=2;
		int temp;
		System.out.println("The value of a is:" +a );
		System.out.println("The value of b is:" +b );
		temp=b;
		b=a;
		a=temp;
		System.out.println("After swapping" );
		System.out.println("The value of a is:" +a );
		System.out.println("The value of b is:" +b );
		
	}
}
